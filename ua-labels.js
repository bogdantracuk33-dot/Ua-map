  /* простий анти-колізійний розкладач: іде від найважливіших підписів
     до менш важливих і пропускає ті, що налазять на вже показані */
  function layout() {
    var z = map.getZoom(), taken = [];
    ITEMS.forEach(function (it) {
      var show = z >= it.z && z <= it.zmax;
      if (show) {
        var pt = map.latLngToLayerPoint(it.ll), w = it.t.length * it.k + 12, h = 18;
        var x1 = it.kind === 'city' ? pt.x - 5 : pt.x - w / 2;
        var x2 = it.kind === 'city' ? pt.x + 9 + w : pt.x + w / 2;
        var y1 = pt.y - h / 2, y2 = pt.y + h / 2;
        for (var i = 0; i < taken.length; i++) {
          var b = taken[i];
          if (!(x2 <= b[0] || x1 >= b[2] || y2 <= b[1] || y1 >= b[3])) { show = false; break; }
        }
        if (show) taken.push([x1, y1, x2, y2]);
      }
      var on = group.hasLayer(it.m);
      if (show && !on) group.addLayer(it.m);
      else if (!show && on) group.removeLayer(it.m);
    });
  }

  map.on('zoomend', layout);
  layout();

